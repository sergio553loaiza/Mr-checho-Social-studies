export function getActivityById(id: string): Activity | undefined {
  const builtIn = ACTIVITIES.find((a) => a.id === id);
  if (builtIn) return builtIn;

  try {
    const raw = typeof window !== 'undefined' ? localStorage.getItem('mrchecho_curriculum_activities_v2') : null;
    if (raw) {
      const custom = JSON.parse(raw);
      if (Array.isArray(custom)) {
        const found = custom.find((a: Activity) => a.id === id);
        if (found) {
          return {
            ...found,
            grade: found.grade || 'both',
            category: found.category || found.topic || 'Social Studies',
          };
        }
      }
    }
  } catch {
    // ignore
  }
  return undefined;
}
